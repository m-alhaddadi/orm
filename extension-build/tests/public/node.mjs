import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const orm = await import(process.env.ORM_EXTENSION_TEST_JS);
const schema = JSON.parse(await readFile(process.env.ORM_EXTENSION_TEST_SCHEMA, "utf8"));
const registry = new orm.Registry();
const { NativeUser: User, NativeRecord: Record, LoweredUser:Lowered, NativeNullable:Nullable } = orm.define(schema, { registry });
assert.equal(User.validateUsername("valid"), undefined);
assert.throws(() => User.validateUsername("bad!"), /username/);
const { NativeUser: GeneratedUser, LoweredUser:GeneratedLowered } = await import(process.env.ORM_EXTENSION_GENERATED);
assert.equal(GeneratedUser.validateUsername("valid"), undefined);
const snapshot = JSON.parse(registry.native().snapshot());
assert.deepEqual(snapshot.tables.find(t => t.name === "native_users").columns.map(c => c.name), ["id", "username"]);
const db = await orm.connect(process.env.ORM_EXTENSION_TEST_URL ?? "sqlite://:memory:", { registry });
await db.createTables();
await db.execute('DELETE FROM "native_users"');
try {
  const nullable = await Nullable.objects.insert({username:null});
  assert.equal(nullable.username,null);
  assert.equal(nullable.display,null);
  await nullable.delete();
  await db.execute("INSERT INTO native_users (username) VALUES ('unrequested')");
  const onlyStored = await User.objects.filter(User.username.eq("unrequested")).select({username:User.username});
  assert.deepEqual(onlyStored,[{username:"unrequested"}]);
  await assert.rejects(() => User.objects.filter(User.username.eq("unrequested")).get(),/must not be computed/);
  await User.objects.filter(User.username.eq("unrequested")).delete();
  const lowered = await Lowered.objects.insert({id:7,publicName:"Alice"});
  assert.equal(lowered.publicName,"Alice");
  assert.equal("secret" in lowered,false);
  const directRegistry = new orm.Registry();
  const physical = structuredClone(schema.models[2]);
  const handwritten = structuredClone(physical);
  handwritten.fields[1].name = "public_name";
  handwritten.fields.pop();
  const {LoweredUser:Direct} = orm.define({dialect:schema.dialect,models:[handwritten],behavior:{schema_contract:1,storage:{models:[physical]}}},{registry:directRegistry});
  assert.equal(Lowered.objects.sql(),Direct.objects.sql());
  assert.deepEqual(JSON.parse(registry.native().snapshot()).tables.find(t=>t.name === "lowered_users"),JSON.parse(directRegistry.native().snapshot()).tables[0]);
  const direct = await Direct.objects.using(db).filter(Direct.id.eq(7)).get();
  const generated = await GeneratedLowered.objects.using(db).filter(GeneratedLowered.id.eq(7)).get();
  assert.equal(direct.publicName,generated.publicName);
  assert.equal(generated.publicName,lowered.publicName);
  await lowered.delete();
  const record = await Record.objects.insert({left:"first",right:"second"});
  await assert.rejects(() => record.update({left:"changed"}), /all non-null supplied dependencies/);
  await record.refresh();
  assert.equal(record.left,"first");
  assert.equal(record.right,"second");
  await record.delete();
  const row = await User.objects.insert({ username: "  alice  " });
  assert.equal(row.username, "alice");
  assert.equal(row.display, "Hello, alice!");
  const generatedRow = await GeneratedUser.objects.using(db).filter(GeneratedUser.id.eq(row.id)).get();
  assert.equal(generatedRow.display, row.display);
  assert.match(User.objects.sql(), /NULL/);
  const projection = await User.objects.select({ display: User.display });
  assert.deepEqual(projection.map(r => [r.display]), [["Hello, alice!"]]);
  await row.update({ username: " bob " });
  assert.equal(row.username, "bob");
  assert.equal(row.display, "Hello, bob!");
  await assert.rejects(async () => User.objects.insertMany([{ username: "good" }, { username: "bad!" }]), /username/);
  assert.equal(await User.objects.count(), 1);
  await assert.rejects(async () => User.objects.insert({ username: " admin " }), /reserved record/);
  await assert.rejects(async () => User.objects.update({ username: null }), /non-null/);
  await assert.rejects(async () => User.objects.filter(User.id.eq(row.id)).update({ username: User.username.add("x") }), /expressions/);
  assert.throws(() => User.objects.filter(User.display.eq("Hello, bob!")).sql(), /computed/);
  const rows = await User.objects.insertMany([{ username: "carol" }, { username: "dave" }]).returning();
  assert.deepEqual(rows.map(r => r.display), ["Hello, carol!", "Hello, dave!"]);
  await User.objects.updateMany([{ id: rows[0].id, username: " eve " }, { id: rows[1].id, username: " frank " }]);
  const loaded = await User.objects.filter(User.id.gte(rows[0].id)).orderBy(User.id);
  assert.deepEqual(loaded.map(r => r.display), ["Hello, eve!", "Hello, frank!"]);
  await db.execute(`UPDATE "native_users" SET username = 'raw!' WHERE id = ${row.id}`);
  const raw = await User.objects.filter(User.id.eq(row.id)).get();
  assert.equal(raw.display, "Hello, raw!!");
} finally {
  await db.dropTables();
  await db.close();
}
const stale = structuredClone(schema);
stale.models[0].fields[1].nullable = true;
assert.throws(() => orm.define(stale, { registry: new orm.Registry() }), /rebuild/);
console.log("TypeScript native extension contract passed");

const ownerSchema = JSON.parse(await readFile(new URL("ownership-schema.json", import.meta.url), "utf8"));
ownerSchema.dialect = schema.dialect;
const physical = structuredClone(ownerSchema.models);
physical[1].fields.pop();
ownerSchema.behavior.storage = {models:physical};
const owners = new orm.Registry();
const {OwnerChild:Child} = orm.define(ownerSchema,{registry:owners});
const ownerDb = await orm.connect(process.env.ORM_EXTENSION_TEST_URL,{registry:owners,default:false});
try {
  await ownerDb.dropTables();
  await ownerDb.createTables();
  await ownerDb.execute("INSERT INTO extension_owner_parents (id, name) VALUES (7, 'Alice')");
  await ownerDb.execute("INSERT INTO extension_owner_children (id, role) VALUES (7, 'employee')");
  const child = await Child.objects.using(ownerDb).get();
  assert.equal(child.name,"Alice");
  assert.equal(child.role,"employee");
  assert.equal(await Child.objects.using(ownerDb).filter(Child.name.eq("Alice")).count(),1);
  assert.deepEqual(await Child.objects.using(ownerDb).select({name:Child.name}),[{name:"Alice"}]);
  await child.refresh();
  assert.equal(child.name,"Alice");
  await assert.rejects(() => child.update({role:"customer"}),/owner statement sequence/);
} finally {
  await ownerDb.dropTables();
  await ownerDb.close();
}
